def get_ffmpeg_binary_path() -> Optional[str]:
    """Return absolute path to ffmpeg binary from imageio_ffmpeg or system PATH, or None."""
    try:
        ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
        if ffmpeg_exe and os.path.exists(ffmpeg_exe):
            return ffmpeg_exe
    except Exception:
        pass
    shutil_path = shutil.which("ffmpeg")
    if shutil_path and os.path.exists(shutil_path):
        return shutil_path
    return None


def build_download_settings(quality: str):
    q_lower = str(quality).lower().strip()
    if q_lower in ("mp3_best", "mp3"):
        return {
            "format": "bestaudio/best",
            "postprocessors": [
                {
                    "key": "FFmpegExtractAudio",
                    "preferredcodec": "mp3",
                    "preferredquality": "192",
                }
            ],
        }
    if q_lower in ("m4a_best", "m4a"):
        return {
            "format": "bestaudio[ext=m4a]/bestaudio/best",
            "postprocessors": [],
        }

    clean_q = q_lower.rstrip('p')
    if clean_q.isdigit():
        h = int(clean_q)
        return {
            "format": f"bestvideo[height<={h}]+bestaudio/best[height<={h}]/b/best",
            "postprocessors": [],
        }

    return {
        "format": "b/best[ext=mp4]/best/bestvideo+bestaudio",
        "postprocessors": [],
    }


def sanitize_filename(name: str, max_len: int = 100) -> str:
    name = "".join(c for c in name if c.isprintable() and c not in '<>:"/\\|?*')
    name = name.strip().rstrip(".")
    if len(name) > max_len:
        name = name[:max_len].rsplit(" ", 1)[0]
    return name or "video"

def short_filename(name: str) -> str:
    """Generate a short, safe filename using a hash to avoid filesystem length limits."""
    h = hashlib.md5(name.encode("utf-8")).hexdigest()[:12]
    sanitized = sanitize_filename(name, max_len=40)
    return f"{sanitized}_{h}" if sanitized else f"video_{h}"


