# ── Dynamic User Cookie Engine ───────────────────────────────────────────────
def create_temp_cookie_file(cookies_data: str, url: str = "") -> Optional[str]:
    """Convert Netscape txt, JSON, or raw key=value cookies into a temporary Netscape format cookie file."""
    if not cookies_data or not cookies_data.strip():
        return None
    raw = cookies_data.strip()
    
    # Check if already Netscape format
    if "# Netscape HTTP Cookie File" in raw or "# HTTP Cookie File" in raw or "\tTRUE\t" in raw or "\tFALSE\t" in raw:
        netscape_content = raw
        if "# Netscape HTTP Cookie File" not in netscape_content:
            netscape_content = "# Netscape HTTP Cookie File\n# http://www.netscape.com/newsref/std/cookie_spec.html\n\n" + netscape_content
    else:
        netscape_lines = [
            "# Netscape HTTP Cookie File",
            "# http://www.netscape.com/newsref/std/cookie_spec.html",
            "# Generated by VidGrab Dynamic Session Engine",
            "",
        ]
        
        # Determine domain from url if available
        domain = ".youtube.com"
        if url:
            u_low = url.lower()
            if "instagram.com" in u_low:
                domain = ".instagram.com"
            elif "facebook.com" in u_low or "fb.watch" in u_low:
                domain = ".facebook.com"
            elif "tiktok.com" in u_low:
                domain = ".tiktok.com"
            elif "twitter.com" in u_low or "x.com" in u_low:
                domain = ".twitter.com"

        expiry = str(int(time.time()) + 30 * 86400) # 30 days expiry

        # Try parsing JSON array of cookies
        is_json = False
        if raw.startswith("[") and raw.endswith("]"):
            try:
                arr = json.loads(raw)
                if isinstance(arr, list):
                    is_json = True
                    for c in arr:
                        if isinstance(c, dict) and "name" in c and "value" in c:
                            c_domain = c.get("domain") or domain
                            if not c_domain.startswith("."):
                                c_domain = "." + c_domain
                            c_path = c.get("path", "/")
                            c_secure = "TRUE" if c.get("secure", True) else "FALSE"
                            c_exp = str(int(c.get("expirationDate", time.time() + 86400 * 30)))
                            netscape_lines.append(f"{c_domain}\tTRUE\t{c_path}\t{c_secure}\t{c_exp}\t{c['name']}\t{c['value']}")
            except Exception:
                is_json = False

        if not is_json:
            # Parse raw cookie string e.g. "sessionid=12345; ds_user_id=6789; csrftoken=abc"
            for item in raw.split(";"):
                item = item.strip()
                if "=" in item:
                    k, v = item.split("=", 1)
                    k = k.strip()
                    v = v.strip()
                    if k and v:
                        netscape_lines.append(f"{domain}\tTRUE\t/\tTRUE\t{expiry}\t{k}\t{v}")

        netscape_content = "\n".join(netscape_lines) + "\n"

    try:
        temp_file = tempfile.NamedTemporaryFile(mode="w", suffix="_cookies.txt", delete=False, encoding="utf-8")
        temp_file.write(netscape_content)
        temp_file.close()
        return temp_file.name
    except Exception:
        return None


def resolve_cookies(
    req: Optional[Request] = None,
    user_cookies_param: Optional[str] = None,
    url: str = ""
) -> Tuple[Optional[str], bool]:
    """Resolve cookie file: prioritizing user-provided session cookies, falling back to server cookies.txt."""
    raw_user_cookies = None
    if user_cookies_param and user_cookies_param.strip():
        raw_user_cookies = user_cookies_param.strip()
    elif req:
        hdr = req.headers.get("x-user-cookies") or req.headers.get("x-custom-cookies")
        if hdr and hdr.strip():
            raw_user_cookies = hdr.strip()

    if raw_user_cookies:
        # Check if URL-encoded
        if "%" in raw_user_cookies:
            try:
                raw_user_cookies = unquote(raw_user_cookies)
            except Exception:
                pass
        temp_path = create_temp_cookie_file(raw_user_cookies, url=url)
        if temp_path:
            return temp_path, True

    # Fallback to server cookies.txt
    return get_valid_cookies_path(), False


